'use strict';
// vfs.js - 3-layer read-only overlay VFS for PocketMZ β runtime:
//   Layer 0: Virtual memory overrides (js/plugins.js + PocketMZ_*.js patches)
//   Layer 1: Writable state/cache dir (gameDir: pmz-cache/, save/, pocketmz.json, pocketmz.gptk)
//   Layer 2: Read-only original game dir (srcDir, with per-directory case-insensitive index cache)

const path = require('path');

function normalizeSlashes(p) {
  return String(p || '').replace(/\\/g, '/');
}

function stripTrailingSlash(p) {
  return p.length > 1 ? p.replace(/\/+$/, '') : p;
}

function isSubPath(targetNorm, baseNorm) {
  if (!baseNorm) return false;
  return targetNorm === baseNorm || targetNorm.startsWith(baseNorm + '/');
}

function makeEnoent(p) {
  const e = new Error("ENOENT: no such file or directory, open '" + p + "'");
  e.code = 'ENOENT';
  e.errno = -2;
  e.path = p;
  return e;
}

function makeErofs(p) {
  const e = new Error("EROFS: read-only original game directory '" + p + "'");
  e.code = 'EROFS';
  e.errno = -30;
  e.path = p;
  return e;
}

function transformPluginsJs(rawText, patchesDir, keepPatches, fsMod) {
  const s = String(rawText || '');
  const i0 = s.indexOf('[');
  const i1 = s.lastIndexOf(']');
  let plugins = [];
  if (i0 >= 0 && i1 >= i0) {
    plugins = JSON.parse(s.slice(i0, i1 + 1));
  }
  plugins = plugins.filter(p => p && p.name && !p.name.startsWith('PocketMZ_') && !p.name.startsWith('GKD_'));

  const keepSet = new Set((keepPatches || []).map(x => String(x)));
  if (patchesDir && fsMod.existsSync(patchesDir)) {
    const files = fsMod.readdirSync(patchesDir)
      .filter(f => f.startsWith('PocketMZ_') && f.endsWith('.js'))
      .sort();
    for (const f of files) {
      const n = f.slice(0, -3);
      if (n === 'PocketMZ_Debug' && !keepSet.has('PocketMZ_Debug')) continue;
      if (keepSet.size > 0 && !keepSet.has(n)) continue;
      plugins.push({ name: n, status: true, description: '', parameters: {} });
    }
    const pj = path.join(patchesDir, 'params.json');
    if (fsMod.existsSync(pj)) {
      const overrides = JSON.parse(fsMod.readFileSync(pj, 'utf8'));
      for (const [name, params] of Object.entries(overrides)) {
        if (name.startsWith('_') || !params || typeof params !== 'object') continue;
        for (const p of plugins) {
          if (p.name === name) {
            p.parameters = Object.assign({}, p.parameters || {}, params);
          }
        }
      }
    }
  }

  return '// Generated by RPG Maker.\n// PocketMZ VFS: PocketMZ_* plugins injected in memory\nvar $plugins =\n[\n' +
    plugins.map(p => JSON.stringify(p)).join(',\n') + '\n];\n';
}

function createVfs(opts) {
  const fsMod = opts.fsMod || require('fs');
  const gameDir = path.resolve(opts.gameDir || '/game');
  const srcDir = opts.srcDir ? path.resolve(opts.srcDir) : '';
  const patchesDir = opts.patchesDir ? path.resolve(opts.patchesDir) : '';
  const keepPatches = Array.isArray(opts.keepPatches) ? opts.keepPatches.slice() : [];

  const gameNorm = stripTrailingSlash(normalizeSlashes(gameDir));
  const srcNorm = srcDir ? stripTrailingSlash(normalizeSlashes(srcDir)) : '';
  const dirIndexCache = new Map();
  let virtualPluginsBuf = null;

  function relFromGame(p) {
    const abs = path.resolve(gameDir, String(p || ''));
    const absNorm = stripTrailingSlash(normalizeSlashes(abs));
    if (absNorm === gameNorm) return '';
    if (absNorm.startsWith(gameNorm + '/')) return absNorm.slice(gameNorm.length + 1);
    return null;
  }

  function getDirIndex(dirPath) {
    let idx = dirIndexCache.get(dirPath);
    if (idx !== undefined) return idx;
    idx = new Map();
    try {
      for (const name of fsMod.readdirSync(dirPath)) {
        const lower = name.toLowerCase();
        if (!idx.has(lower)) idx.set(lower, name);
      }
    } catch (_) {
      idx = null;
    }
    dirIndexCache.set(dirPath, idx);
    return idx;
  }

  function resolveInDirCaseInsensitive(baseDir, relPath) {
    if (!baseDir) return null;
    const direct = relPath ? path.join(baseDir, relPath) : baseDir;
    if (fsMod.existsSync(direct)) return direct;
    if (!relPath) return null;
    const segs = relPath.split('/').filter(Boolean);
    let cur = baseDir;
    for (const seg of segs) {
      const exact = path.join(cur, seg);
      if (fsMod.existsSync(exact)) {
        cur = exact;
        continue;
      }
      const idx = getDirIndex(cur);
      if (!idx) return null;
      const hit = idx.get(seg.toLowerCase());
      if (!hit) return null;
      cur = path.join(cur, hit);
    }
    return fsMod.existsSync(cur) ? cur : null;
  }

  function getVirtualPluginsBuffer() {
    if (virtualPluginsBuf !== null) return virtualPluginsBuf;
    const gamePjs = path.join(gameDir, 'js', 'plugins.js');
    let raw = 'var $plugins = [];\n';
    if (fsMod.existsSync(gamePjs)) {
      raw = fsMod.readFileSync(gamePjs, 'utf8');
    } else if (srcDir) {
      const srcPjs = resolveInDirCaseInsensitive(srcDir, 'js/plugins.js');
      if (srcPjs) raw = fsMod.readFileSync(srcPjs, 'utf8');
    }
    virtualPluginsBuf = Buffer.from(transformPluginsJs(raw, patchesDir, keepPatches, fsMod), 'utf8');
    return virtualPluginsBuf;
  }

  function isVirtualPluginsJs(p) {
    if (!patchesDir) return false;
    const rel = relFromGame(p);
    return rel !== null && rel.toLowerCase() === 'js/plugins.js';
  }

  function resolveVirtualPatch(rel) {
    if (!patchesDir || !rel) return null;
    const m = /^js\/plugins\/(PocketMZ_[^/]+\.js)$/i.exec(rel);
    if (!m) return null;
    const exact = path.join(patchesDir, m[1]);
    if (fsMod.existsSync(exact)) return exact;
    const idx = getDirIndex(patchesDir);
    const hit = idx && idx.get(m[1].toLowerCase());
    return hit ? path.join(patchesDir, hit) : null;
  }

  function resolveRead(p) {
    const rel = relFromGame(p);
    if (rel === null) {
      const abs = path.resolve(String(p || ''));
      return fsMod.existsSync(abs) ? { kind: 'file', path: abs } : null;
    }

    // Layer 0: Virtual memory overrides
    if (patchesDir && rel.toLowerCase() === 'js/plugins.js') {
      return { kind: 'virtual', data: getVirtualPluginsBuffer(), path: path.join(gameDir, 'js', 'plugins.js') };
    }
    const patchFile = resolveVirtualPatch(rel);
    if (patchFile) return { kind: 'file', path: patchFile };

    // Layer 1: Writable state/cache dir (gameDir)
    const inGame = rel ? path.join(gameDir, rel) : gameDir;
    if (fsMod.existsSync(inGame)) return { kind: 'file', path: inGame };

    // Layer 2: Read-only original game dir (srcDir, case-insensitive)
    if (srcDir) {
      const inSrc = resolveInDirCaseInsensitive(srcDir, rel);
      if (inSrc) return { kind: 'file', path: inSrc };
    }
    return null;
  }

  function resolvePath(p) {
    const r = resolveRead(p);
    if (r && r.kind === 'file') return r.path;
    return path.resolve(gameDir, String(p || ''));
  }

  function existsSync(p) {
    return resolveRead(p) !== null;
  }

  function statSync(p, opts2) {
    const r = resolveRead(p);
    if (!r) throw makeEnoent(p);
    if (r.kind === 'virtual') {
      const base = fsMod.existsSync(gameDir) ? fsMod.statSync(gameDir) : fsMod.statSync(srcDir || __dirname);
      return Object.assign(Object.create(Object.getPrototypeOf(base)), base, {
        size: r.data.length,
        isFile: () => true,
        isDirectory: () => false,
        isSymbolicLink: () => false,
      });
    }
    return fsMod.statSync(r.path, opts2);
  }

  function readFileSync(p, opts2) {
    const r = resolveRead(p);
    if (!r) throw makeEnoent(p);
    if (r.kind === 'virtual') {
      const enc = typeof opts2 === 'string' ? opts2 : (opts2 && opts2.encoding);
      return enc ? r.data.toString(enc) : Buffer.from(r.data);
    }
    return fsMod.readFileSync(r.path, opts2);
  }

  function readFile(p, opts2, cb) {
    if (typeof opts2 === 'function') { cb = opts2; opts2 = undefined; }
    const r = resolveRead(p);
    if (!r) return process.nextTick(() => cb(makeEnoent(p)));
    if (r.kind === 'virtual') {
      const enc = typeof opts2 === 'string' ? opts2 : (opts2 && opts2.encoding);
      const out = enc ? r.data.toString(enc) : Buffer.from(r.data);
      return process.nextTick(() => cb(null, out));
    }
    return fsMod.readFile(r.path, opts2, cb);
  }

  function readFilePromises(p, opts2) {
    const r = resolveRead(p);
    if (!r) return Promise.reject(makeEnoent(p));
    if (r.kind === 'virtual') {
      const enc = typeof opts2 === 'string' ? opts2 : (opts2 && opts2.encoding);
      return Promise.resolve(enc ? r.data.toString(enc) : Buffer.from(r.data));
    }
    return fsMod.promises.readFile(r.path, opts2);
  }

  function readdirSync(p, opts2) {
    const rel = relFromGame(p);
    if (rel === null) return fsMod.readdirSync(p, opts2);

    const merged = new Map();
    const addFrom = dir => {
      if (!dir || !fsMod.existsSync(dir)) return;
      try {
        for (const item of fsMod.readdirSync(dir, opts2)) {
          const key = typeof item === 'string' ? item : item.name;
          if (!merged.has(key)) merged.set(key, item);
        }
      } catch (_) {}
    };

    addFrom(rel ? path.join(gameDir, rel) : gameDir);
    if (srcDir) {
      const srcSub = resolveInDirCaseInsensitive(srcDir, rel);
      addFrom(srcSub);
    }
    if (patchesDir && rel.toLowerCase() === 'js/plugins') {
      try {
        for (const f of fsMod.readdirSync(patchesDir)) {
          if (f.startsWith('PocketMZ_') && f.endsWith('.js') && !merged.has(f)) {
            if (opts2 && opts2.withFileTypes) {
              merged.set(f, { name: f, isFile: () => true, isDirectory: () => false, isSymbolicLink: () => false });
            } else {
              merged.set(f, f);
            }
          }
        }
      } catch (_) {}
    }
    if (merged.size === 0 && !existsSync(p)) throw makeEnoent(p);
    return [...merged.values()];
  }

  function assertNotSrcWrite(p) {
    if (!srcNorm) return;
    const absNorm = stripTrailingSlash(normalizeSlashes(path.resolve(gameDir, String(p || ''))));
    if (isSubPath(absNorm, srcNorm)) throw makeErofs(p);
  }

  function createFsProxy() {
    const promisesProxy = new Proxy(fsMod.promises, {
      get(t, k) {
        if (k === 'readFile') return readFilePromises;
        if (k === 'stat') return async (p, o) => statSync(p, o);
        const v = t[k];
        return typeof v === 'function' ? v.bind(t) : v;
      },
    });
    return new Proxy(fsMod, {
      get(t, k) {
        if (k === 'promises') return promisesProxy;
        if (k === 'existsSync') return existsSync;
        if (k === 'statSync') return statSync;
        if (k === 'lstatSync') {
          return (p, o) => {
            const abs = path.resolve(gameDir, String(p || ''));
            if (fsMod.existsSync(abs)) return fsMod.lstatSync(abs, o);
            return statSync(p, o);
          };
        }
        if (k === 'readFileSync') return readFileSync;
        if (k === 'readFile') return readFile;
        if (k === 'readdirSync') return readdirSync;
        if (k === 'createReadStream') {
          return (p, o) => {
            const r = resolveRead(p);
            if (!r || r.kind === 'virtual') return t.createReadStream(p, o);
            return t.createReadStream(r.path, o);
          };
        }
        if (k === 'writeFileSync' || k === 'appendFileSync' || k === 'mkdirSync' || k === 'unlinkSync' || k === 'rmSync' || k === 'rmdirSync') {
          return (p, ...rest) => { assertNotSrcWrite(p); return t[k](p, ...rest); };
        }
        if (k === 'renameSync' || k === 'copyFileSync') {
          return (a, b, ...rest) => { assertNotSrcWrite(b); return t[k](a, b, ...rest); };
        }
        if (k === 'writeFile') {
          return (p, ...rest) => { assertNotSrcWrite(p); return t.writeFile(p, ...rest); };
        }
        const v = t[k];
        return typeof v === 'function' ? v.bind(t) : v;
      },
    });
  }

  return {
    gameDir,
    srcDir,
    patchesDir,
    isVirtualPluginsJs,
    resolveRead,
    resolvePath,
    existsSync,
    statSync,
    readFileSync,
    readFile,
    readFilePromises,
    readdirSync,
    createFsProxy,
  };
}

module.exports = { createVfs, transformPluginsJs };
