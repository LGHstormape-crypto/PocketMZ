#!/bin/sh
# Build a thin writable copy of an RPG Maker MV/MZ game.
# Usage: pocketmz-mkgame.sh <original game dir> <work dir>
# Layout: MZ has index.html in the game folder; MV has package.json there and the game in www/.
# Copies small, patchable files (index.html, package.json, css/, js/, data/) to <work dir>;
# big asset folders become symlinks to /gamesrc/[www/]<name> (the original, bound read-only
# into the chroot by pocketmz-chroot.sh with POCKETMZ_SRC=<original game dir>).
# Windows runtime files (*.exe, *.dll, *.pak, locales, swiftshader ...) are skipped.
# PocketMZ_Debug.js (dev REPL) is only added when /storage/pocketmz/dev exists.
set -e
SRC="$1"; DST="$2"
PMZ="$(cd "$(dirname "$(readlink -f "$0")")" && pwd)"   # program files: patches, fonts.py
RZ="${POCKETMZ_DATA:-/storage/pocketmz}"                 # data: dev flag, browser profiles
if [ -f "$SRC/index.html" ]; then WEB=""
elif [ -f "$SRC/www/index.html" ]; then WEB="www/"
else echo "no index.html or www/index.html in $SRC" >&2; exit 1; fi
mkdir -p "$DST/$WEB"
cp -f "$SRC/package.json" "$DST/package.json"
cp -f "$SRC/${WEB}index.html" "$DST/${WEB}index.html"
for d in css js data; do
  [ -d "$SRC/$WEB$d" ] || continue
  rm -rf "$DST/$WEB$d.tmp"; cp -r "$SRC/$WEB$d" "$DST/$WEB$d.tmp"
  rm -rf "$DST/$WEB$d"; mv "$DST/$WEB$d.tmp" "$DST/$WEB$d"
done
for d in "$SRC/$WEB"*/; do
  [ -d "$d" ] || continue
  n=$(basename "$d")
  case "$n" in css|js|data|locales|swiftshader|save|www) continue ;; esac
  [ "$n" = fonts ] && [ -d "$DST/${WEB}fonts" ] && [ ! -L "$DST/${WEB}fonts" ] && continue   # subset dir
  [ -e "$DST/$WEB$n" ] && [ ! -L "$DST/$WEB$n" ] && continue
  ln -sfn "/gamesrc/$WEB$n" "$DST/$WEB$n"
done
# handheld patches: copy PocketMZ_*.js plugins, register them last in js/plugins.js and apply
# plugin parameter overrides from patches/params.json ({"Plugin": {"param": "value"}}).
PATCHES="${POCKETMZ_PATCHES:-$PMZ/patches}"
DEV=0; [ -f "$RZ/dev" ] && DEV=1
rm -f "$DST/${WEB}js/plugins/PocketMZ_"*.js "$DST/${WEB}js/plugins/GKD_"*.js   # GKD_: name before 2026-11-19
for p in "$PATCHES"/PocketMZ_*.js; do
  [ -f "$p" ] || continue
  [ "$(basename "$p")" = PocketMZ_Debug.js ] && [ "$DEV" = 0 ] && continue
  cp -f "$p" "$DST/${WEB}js/plugins/"
done
python3 - "$DST/${WEB}js/plugins.js" "$PATCHES" "$DEV" <<'PY'
import json, os, sys, glob
path, patches, dev = sys.argv[1], sys.argv[2], sys.argv[3] == "1"
s = open(path, encoding="utf-8").read()
plugins = json.loads(s[s.index("["):s.rindex("]") + 1])
plugins = [p for p in plugins if not p["name"].startswith(("PocketMZ_", "GKD_"))]   # re-added below, in order
for f in sorted(glob.glob(os.path.join(patches, "PocketMZ_*.js"))):
    n = os.path.basename(f)[:-3]
    if n == "PocketMZ_Debug" and not dev:
        continue
    plugins.append({"name": n, "status": True, "description": "", "parameters": {}})
pj = os.path.join(patches, "params.json")
if os.path.exists(pj):
    for name, params in json.load(open(pj, encoding="utf-8")).items():
        if name.startswith("_"):
            continue
        for p in plugins:
            if p["name"] == name:
                for k, v in params.items():
                    print("param %s.%s: %r -> %r" % (name, k, p["parameters"].get(k), v))
                    p["parameters"][k] = v
# Plugin files whose name differs only in case from plugins.js (works on Windows, not on
# ext4): add a symlink with the expected name.
pdir = os.path.join(os.path.dirname(path), "plugins")
try:
    files = {f.lower(): f for f in os.listdir(pdir)}
except OSError:
    files = {}
for p in plugins:
    want = p["name"] + ".js"
    if not os.path.exists(os.path.join(pdir, want)):
        have = files.get(want.lower())
        if have:
            os.symlink(have, os.path.join(pdir, want))
            print("case fix: js/plugins/%s -> %s" % (want, have))
        elif p.get("status"):
            print("WARNING: plugin file missing: js/plugins/%s" % want)
out = "// Generated by RPG Maker.\n// PocketMZ: PocketMZ_* plugins added, see patches/params.json\nvar $plugins =\n[\n"
out += ",\n".join(json.dumps(p, ensure_ascii=False, separators=(",", ":")) for p in plugins)
open(path, "w", encoding="utf-8").write(out + "\n];\n")
PY
# NW.js app name = browser profile folder and Wayland app_id (sway fullscreen rule). Many games
# keep a default name ("rmmz-game", MV ""), so new games get "pocketmz-<id>"; a game that already
# has a profile under its own name keeps it. The choice is stored in <work dir>/../appname.
ID=$(basename "$(dirname "$DST")")
APPF="$(dirname "$DST")/appname"
ORIG=$(python3 -c 'import json,sys; print(json.load(open(sys.argv[1], encoding="utf-8-sig")).get("name",""))' "$SRC/package.json" 2>/dev/null)
if [ ! -f "$APPF" ]; then
  if [ -n "$ORIG" ] && [ -d "$RZ/home/.config/$ORIG" ]; then echo "$ORIG" > "$APPF"
  else echo "pocketmz-$(printf %s "$ID" | tr 'A-Z' 'a-z' | tr -c 'a-z0-9._-' '-')" > "$APPF"; fi
fi
python3 - "$DST/package.json" "$(cat "$APPF")" <<'PY'
import json, sys
path, name = sys.argv[1], sys.argv[2]
d = json.load(open(path, encoding="utf-8-sig"))
if d.get("name") != name:
    print("app name: %r -> %r" % (d.get("name"), name))
    d["name"] = name
    json.dump(d, open(path, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
PY
# fonts: subset the ones the game uses (host python3 + pure-Python fontTools from the image,
# falling back to chroot python3 if needed; MZ layout); keep the symlink on failure.
# (once per game: an existing subset folder is kept; POCKETMZ_SUBSET_FONTS=force redoes it)
if [ -z "$WEB" ] && [ -d "$SRC/fonts" ] && [ "${POCKETMZ_SUBSET_FONTS:-1}" != 0 ] && \
   { [ "$POCKETMZ_SUBSET_FONTS" = force ] || [ -L "$DST/fonts" ] || [ ! -d "$DST/fonts" ]; }; then
  "$PMZ/pocketmz-chroot.sh" mount >/dev/null 2>&1 || true
  FT_DIR=""
  for d in "$RZ/root-test/usr/lib/python3/dist-packages" "$RZ/root-sqfs/usr/lib/python3/dist-packages" "$RZ/rootfs/usr/lib/python3/dist-packages"; do
    [ -d "$d/fontTools" ] && { FT_DIR="$d"; break; }
  done
  if [ -n "$FT_DIR" ] && command -v python3 >/dev/null 2>&1; then
    PYTHONPATH="$FT_DIR" POCKETMZ_FONT_SRC="$SRC" POCKETMZ_FONT_DST="$DST" python3 "$PMZ/pocketmz-fonts.py" \
      || { echo "font subset failed, using original fonts"; rm -rf "$DST/fonts"; ln -sfn /gamesrc/fonts "$DST/fonts"; }
  else
    POCKETMZ_GAME="$DST" POCKETMZ_SRC="$SRC" "$PMZ/pocketmz-chroot.sh" run python3 - < "$PMZ/pocketmz-fonts.py" \
      || { echo "font subset failed, using original fonts"; rm -rf "$DST/fonts"; ln -sfn /gamesrc/fonts "$DST/fonts"; }
  fi
fi
# keep existing saves (MZ: <game>/save/, MV: <game>/www/save/); never overwrite the copy's saves
mkdir -p "$DST/${WEB}save"
[ -d "$SRC/${WEB}save" ] && [ -z "$(ls -A "$DST/${WEB}save")" ] && cp -r "$SRC/${WEB}save/." "$DST/${WEB}save/"
LAYOUT=MZ; [ -n "$WEB" ] && LAYOUT=MV
echo "thin copy ready: $DST ($LAYOUT layout, dev=$DEV)"
